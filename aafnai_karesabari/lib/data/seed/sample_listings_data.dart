import '../models/listing.dart';

/// A curated catalogue of common Nepali agricultural products.
///
/// Deliberately carries no photo URLs — the marketplace renders a vector
/// icon per item (see `iconForListing`) instead of uploading images, which
/// keeps the app comfortably inside the Firebase Spark (free) plan's
/// Storage quota. Only the fields needed to list and browse a product are
/// included.
class SampleListingData {
  const SampleListingData({
    required this.productName,
    required this.category,
    required this.pricePerUnit,
    required this.unit,
    required this.stockQuantity,
    required this.location,
    this.description,
  });

  final String productName;
  final ListingCategory category;
  final double pricePerUnit;
  final ListingUnit unit;
  final int stockQuantity;
  final String location;
  final String? description;

  String get slug => productName
      .toLowerCase()
      .replaceAll(RegExp(r'[^a-z0-9]+'), '-')
      .replaceAll(RegExp(r'(^-+)|(-+$)'), '');
}

